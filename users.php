$role = current_role();
$uid  = (int) ($_SESSION['user_id'] ?? 0);

const CREATABLE_ROLES_BY_ROLE = [
    'it_admin'   => ['bd_officer', 'bd_manager', 'management', 'account_manager', 'it_admin', 'auditor'],
    'management' => ['bd_officer', 'bd_manager', 'management', 'account_manager', 'it_admin', 'auditor'],
];
$creatableRoles = CREATABLE_ROLES_BY_ROLE[$role];

$error   = '';
$success = '';

// ── Create user + assign credentials ─────────────────────────────────────
if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['action'] ?? '') === 'create_user') {
    $name          = trim($_POST['name']     ?? '');
    $email         = trim($_POST['email']    ?? '');
    $newRole       = $_POST['role']          ?? '';
    $setPassword   = $_POST['password']      ?? '';
    $autoGenerated = false;

    if ($name === '' || !filter_var($email, FILTER_VALIDATE_EMAIL)) {
        $error = 'Please provide a valid name and email.';
    } elseif (!in_array($newRole, $creatableRoles, true)) {
        $error = 'You are not permitted to create a user with that role.';
    } elseif ($setPassword !== '' && strlen($setPassword) < 8) {
        $error = 'Password must be at least 8 characters — leave it blank to auto-generate one instead.';
    } else {
        $existing = $pdo->prepare('SELECT id FROM users WHERE email = ?');
        $existing->execute([$email]);
        if ($existing->fetch()) {
            $error = 'A user with that email already exists.';
        } else {
            if ($setPassword === '') {
                $setPassword   = bin2hex(random_bytes(5));
                $autoGenerated = true;
            }
            $hash = password_hash($setPassword, PASSWORD_BCRYPT);
            $stmt = $pdo->prepare('INSERT INTO users (name, email, password_hash, role, status) VALUES (?,?,?,?,"active")');
            $stmt->execute([$name, $email, $hash, $newRole]);
            $newId = (int) $pdo->lastInsertId();

            $audit = $pdo->prepare('INSERT INTO audit_log (user_id, action, entity_type, entity_id, details) VALUES (?,?,?,?,?)');
            $audit->execute([$uid, 'create', 'user', $newId, "Created user $email ({$newRole}) — credentials assigned by " . e(current_role_label())]);

            $success = ($autoGenerated ? 'User created with an auto-generated password: ' : 'User created with the password you assigned: ')
                . '<code>' . e($setPassword) . '</code> — share this with them securely and ask them to sign in and note it down.';
        }
    }
}

// ── Suspend / reactivate ──────────────────────────────────────────────────
if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['action'] ?? '') === 'toggle_status') {
    $targetId   = (int) ($_POST['user_id'] ?? 0);
    $targetStmt = $pdo->prepare('SELECT role, status FROM users WHERE id = ?');
    $targetStmt->execute([$targetId]);
    $target = $targetStmt->fetch();

    if ($targetId === $uid) {
        $error = "You can't suspend your own account.";
    } elseif (!$target) {
        $error = 'User not found.';
    } elseif (!in_array($target['role'], $creatableRoles, true)) {
        $error = 'You are not permitted to manage a user with that role.';
    } else {
        $newStatus = $target['status'] === 'active' ? 'suspended' : 'active';
        $pdo->prepare('UPDATE users SET status = ? WHERE id = ?')->execute([$newStatus, $targetId]);

        $audit = $pdo->prepare('INSERT INTO audit_log (user_id, action, entity_type, entity_id, details) VALUES (?,?,?,?,?)');
        $audit->execute([$uid, 'update', 'user', $targetId, "Status changed to $newStatus"]);

        $success = 'User status updated.';
    }
}

// ── Change password (admin sets a specific new password) ──────────────────
if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['action'] ?? '') === 'change_password') {
    $targetId    = (int) ($_POST['user_id']        ?? 0);
    $newPassword = trim($_POST['new_password']     ?? '');
    $confirmPass = trim($_POST['confirm_password'] ?? '');

    $targetStmt = $pdo->prepare('SELECT role, name FROM users WHERE id = ?');
    $targetStmt->execute([$targetId]);
    $target = $targetStmt->fetch();

    if (!$target || !in_array($target['role'], $creatableRoles, true)) {
        $error = 'You are not permitted to change the password for that user.';
    } elseif ($newPassword === '') {
        $error = 'Please enter a new password.';
    } elseif (strlen($newPassword) < 8) {
        $error = 'Password must be at least 8 characters.';
    } elseif ($newPassword !== $confirmPass) {
        $error = 'Passwords do not match — please try again.';
    } else {
        $hash = password_hash($newPassword, PASSWORD_BCRYPT);
        $pdo->prepare('UPDATE users SET password_hash = ? WHERE id = ?')->execute([$hash, $targetId]);

        $audit = $pdo->prepare('INSERT INTO audit_log (user_id, action, entity_type, entity_id, details) VALUES (?,?,?,?,?)');
        $audit->execute([$uid, 'update', 'user', $targetId, 'Password changed by ' . e(current_role_label())]);

        $success = 'Password updated for <strong>' . e($target['name']) . '</strong>. Share the new password with them securely.';
    }
}

