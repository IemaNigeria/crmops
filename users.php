    $targetStmt = $pdo->prepare('SELECT role, name FROM users WHERE id = ?');
    $targetStmt->execute([$targetId]);
    $target = $targetStmt->fetch();

    if ($targetId === $uid) {
        $error = "You can't change your own role.";
    } elseif (!$target) {
        $error = 'User not found.';
    } elseif (!in_array($target['role'], $creatableRoles, true)) {
        $error = 'You are not permitted to manage a user with that role.';
    } elseif (!in_array($newRole, $creatableRoles, true)) {
        $error = 'You are not permitted to assign that role.';
    } elseif ($newRole === $target['role']) {
        $error = 'User already has that role — no change made.';
    } else {
        $pdo->prepare('UPDATE users SET role = ? WHERE id = ?')->execute([$newRole, $targetId]);

        $audit = $pdo->prepare('INSERT INTO audit_log (user_id, action, entity_type, entity_id, details) VALUES (?,?,?,?,?)');
        $audit->execute([$uid, 'update', 'user', $targetId,
            "Role changed from {$target['role']} to {$newRole} by " . e(current_role_label())]);

        $success = 'Role updated for <strong>' . e($target['name']) . '</strong>.';
    }
}

