// ── Password strength indicator ───────────────────────────────────────────
function updateStrength(val) {
  const bar  = document.getElementById('pwStrengthBar');
  const hint = document.getElementById('pwHint');
  let score  = 0;

  if (val.length >= 8)                               score++;
  if (val.length >= 12)                              score++;
  if (/[A-Z]/.test(val) && /[a-z]/.test(val))       score++;
  if (/[0-9]/.test(val))                             score++;
  if (/[^A-Za-z0-9]/.test(val))                     score++;

  const levels = [
    { pct: '0%',   bg: 'transparent',               label: 'At least 8 characters' },
    { pct: '25%',  bg: '#ef4444',                   label: 'Weak'   },
    { pct: '50%',  bg: '#f97316',                   label: 'Fair'   },
    { pct: '75%',  bg: '#eab308',                   label: 'Good'   },
    { pct: '100%', bg: 'var(--green-600,#16a34a)',  label: 'Strong' },
  ];

  const level = val.length === 0 ? levels[0] : levels[Math.min(score, 4)];
  bar.style.width      = level.pct;
  bar.style.background = level.bg;
  hint.textContent     = val.length === 0 ? 'At least 8 characters' : level.label;
  hint.style.color     = val.length === 0 ? 'var(--ink-400)' : level.bg;
}

// ── Live password match feedback ──────────────────────────────────────────
function updatePwMatch() {
  const hint  = document.getElementById('pwMatchHint');
  const val   = document.getElementById('pwConfirm').value;
  if (val === '') { hint.textContent = ''; return; }
  const match = val === document.getElementById('pwNew').value;
  hint.textContent = match ? '✓ Passwords match' : '✗ Passwords do not match';
  hint.style.color = match ? 'var(--green-600,#16a34a)' : '#ef4444';
}

// ── Client-side validation before password submit ─────────────────────────
function validatePwForm() {
  const pw      = document.getElementById('pwNew').value;
  const confirm = document.getElementById('pwConfirm').value;
  const hint    = document.getElementById('pwHint');
  const mHint   = document.getElementById('pwMatchHint');

  if (pw.length < 8) {
    hint.textContent = 'Password must be at least 8 characters.';
    hint.style.color = '#ef4444';
    document.getElementById('pwNew').focus();
    return false;
  }
  if (pw !== confirm) {
    mHint.textContent = '✗ Passwords do not match';
    mHint.style.color = '#ef4444';
    document.getElementById('pwConfirm').focus();
    return false;
  }
  return true;
}

